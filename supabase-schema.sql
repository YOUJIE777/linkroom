-- Linkroom shared workspace schema (Supabase / PostgreSQL)
-- Apply in a fresh Supabase project. Access is restricted to authenticated workspace members.
create extension if not exists pgcrypto;

create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','editor','viewer')),
  created_at timestamptz not null default now(),
  primary key (workspace_id,user_id)
);

create table if not exists public.batches (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.records (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  batch_id uuid references public.batches(id) on delete set null,
  display_id bigint generated by default as identity,
  url text not null,
  note text not null default '',
  status text not null default '待处理' check (status in ('待处理','处理中','待确认','已通过','未通过','账号受限')),
  assignee uuid references auth.users(id) on delete set null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create index if not exists records_workspace_batch_idx on public.records(workspace_id,batch_id,created_at desc);
create index if not exists records_workspace_status_idx on public.records(workspace_id,status);
create unique index if not exists records_workspace_url_unique on public.records(workspace_id,lower(url));

create table if not exists public.attachments (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  record_id uuid not null references public.records(id) on delete cascade,
  storage_path text not null unique,
  original_name text not null,
  content_type text not null check (content_type in ('image/jpeg','image/png','image/webp','image/heic','application/pdf')),
  size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 15728640),
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.record_activity (
  id bigint generated always as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  record_id uuid references public.records(id) on delete set null,
  actor uuid not null references auth.users(id) on delete restrict,
  action text not null,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

-- Bootstrap the first workspace and owner after the tables/policies have been created.
-- Replace the email below with the owner account shown in Authentication → Users,
-- then run this block once from the Supabase SQL Editor (project owner context).
do $$
declare
  owner_user_id uuid;
  owner_workspace_id uuid;
begin
  select id into owner_user_id from auth.users where lower(email)=lower('OWNER_EMAIL@example.com') limit 1;
  if owner_user_id is null then
    raise exception 'Owner account not found. Create/sign in the Auth user first, then rerun this block.';
  end if;

  select id into owner_workspace_id from public.workspaces where name='Linkroom 工作区' and created_by=owner_user_id limit 1;
  if owner_workspace_id is null then
    insert into public.workspaces(name,created_by) values ('Linkroom 工作区',owner_user_id) returning id into owner_workspace_id;
  end if;

  insert into public.workspace_members(workspace_id,user_id,role)
  values (owner_workspace_id,owner_user_id,'admin')
  on conflict (workspace_id,user_id) do update set role='admin';

  insert into public.batches(workspace_id,name,created_by)
  select owner_workspace_id,batch_name,owner_user_id
  from (values ('待分配'),('10 月 · 第一批'),('11 月 · 第二批')) as defaults(batch_name)
  where not exists (select 1 from public.batches b where b.workspace_id=owner_workspace_id and b.name=defaults.batch_name);
end $$;

create or replace function public.is_workspace_member(target_workspace uuid)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.workspace_members m where m.workspace_id=target_workspace and m.user_id=auth.uid()) $$;

create or replace function public.can_edit_workspace(target_workspace uuid)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.workspace_members m where m.workspace_id=target_workspace and m.user_id=auth.uid() and m.role in ('admin','editor')) $$;

alter table public.workspaces enable row level security;
alter table public.workspace_members enable row level security;
alter table public.batches enable row level security;
alter table public.records enable row level security;
alter table public.attachments enable row level security;
alter table public.record_activity enable row level security;

create policy "members can view their workspaces" on public.workspaces for select using (public.is_workspace_member(id));
create policy "admins can create workspace" on public.workspaces for insert with check (created_by=auth.uid());
create policy "members can view workspace members" on public.workspace_members for select using (public.is_workspace_member(workspace_id));
create policy "members can view batches" on public.batches for select using (public.is_workspace_member(workspace_id));
create policy "editors can create batches" on public.batches for insert with check (public.can_edit_workspace(workspace_id) and created_by=auth.uid());
create policy "editors can update batches" on public.batches for update using (public.can_edit_workspace(workspace_id)) with check (public.can_edit_workspace(workspace_id));
create policy "members can view records" on public.records for select using (public.is_workspace_member(workspace_id));
create policy "editors can create records" on public.records for insert with check (public.can_edit_workspace(workspace_id) and created_by=auth.uid());
create policy "editors can update records" on public.records for update using (public.can_edit_workspace(workspace_id)) with check (public.can_edit_workspace(workspace_id) and updated_by=auth.uid());
create policy "editors can delete records" on public.records for delete using (public.can_edit_workspace(workspace_id));
create policy "members can view attachment metadata" on public.attachments for select using (public.is_workspace_member(workspace_id));
create policy "editors can add attachment metadata" on public.attachments for insert to authenticated with check (public.can_edit_workspace(workspace_id) and uploaded_by=auth.uid() and storage_path like workspace_id::text || '/' || record_id::text || '/%' and exists (select 1 from public.records r where r.id=record_id and r.workspace_id=attachments.workspace_id));
create policy "members can view activity" on public.record_activity for select using (public.is_workspace_member(workspace_id));
create policy "editors can add activity" on public.record_activity for insert with check (public.can_edit_workspace(workspace_id) and actor=auth.uid());

